import { chromium } from '@playwright/test';

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
await context.addInitScript(() => { localStorage.setItem('agripos_access_token', 'test'); localStorage.setItem('agripos_refresh_token', 'test'); });
await context.route('**/api/v1/**', async route => {
  const url = new URL(route.request().url());
  let data = {};
  if (url.pathname.endsWith('/auth/profile')) data = { id: 'u1', fullName: 'Chủ đại lý', role: 'owner', organizationId: 'org1', isActive: true };
  else if (url.pathname.endsWith('/marketplace/dealers')) data = [];
  else if (url.pathname.endsWith('/notifications')) data = { items: [], unread: 0 };
  else if (url.pathname.endsWith('/agrilink-manage/orders')) data = { items: [], total: 0, counts: { pending: 0, confirmed: 0, delivering: 0, completed: 0, rejected: 0, cancelled: 0 } };
  else if (url.pathname.endsWith('/store-settings')) data = { storeName: 'Đại lý thử' };
  await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ success: true, data }) });
});
const page = await context.newPage();
await page.goto('http://127.0.0.1:5173/agrilink');
await page.getByText('Khám phá đại lý').first().waitFor();
console.log('AgriLink desktop sidebar', await page.locator('.agrilink-sidebar').isVisible());
await page.setViewportSize({ width: 390, height: 844 });
console.log('AgriLink mobile bottom nav', await page.locator('.agrilink-bottom-nav').isVisible(), 'overflow', await page.evaluate(() => document.documentElement.scrollWidth > innerWidth));
await page.goto('http://127.0.0.1:5173/pos');
await page.getByText('Về AgriPOS').waitFor();
