await page.setViewportSize({ width: 1280, height: 800 });
await page.goto('http://127.0.0.1:5173/sales-list');
await page.waitForTimeout(2000);
console.log('AgriPOS menu visible', await page.locator('[data-group="agrilink"] button').first().isVisible());
await page.locator('[data-group="agrilink"] button').first().click({ timeout: 5000 });
console.log('named tab pages', context.pages().length);
await page.locator('[data-group="agrilink"] button').first().click({ timeout: 5000 });
